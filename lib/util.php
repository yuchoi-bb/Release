function current_lang(): string
{
    if (isset($_GET['lang'])) {
        $lang = $_GET['lang'] === 'ko' ? 'ko' : 'en';
        setcookie('th_lang', $lang, ['expires' => time() + 86400 * 365, 'path' => base_path(), 'samesite' => 'Lax']);
        return $lang;
    }
    return ($_COOKIE['th_lang'] ?? 'en') === 'ko' ? 'ko' : 'en';
}

/** 번역 문자열. 추가 인자는 sprintf 로 채워집니다. */
function tr(string $lang, string $key, ...$args): string
{
    $s = I18N[$lang][$key] ?? I18N['en'][$key] ?? $key;
    if (!is_string($s)) {
        return $key;
    }
    return $args ? vsprintf($s, $args) : $s;
}

/**
 * 페이지가 놓인 하위 경로(예: /release/).
 * 쿠키 경로를 여기로 제한해 같은 도메인의 다른 페이지와 섞이지 않게 합니다.
 */
function base_path(): string
{
    $dir = str_replace('\\', '/', dirname((string)($_SERVER['SCRIPT_NAME'] ?? '/')));
    $dir = rtrim($dir, '/');
    // api/ 안에서 호출되면 한 단계 올라가 프로젝트 루트를 가리키게 합니다.
    if (str_ends_with($dir, '/api')) {
        $dir = substr($dir, 0, -4);
    }
    return ($dir === '' ? '' : $dir) . '/';
}

/** JSON 응답을 내보내고 종료합니다. */
function json_out(array $payload, int $status = 200): never
{
    http_response_code($status);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode($payload, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    exit;
}
