/** HTML 이스케이프. 화면에 값을 찍을 때는 예외 없이 이걸 통과시킵니다. */
function e(?string $s): string
{
    return htmlspecialchars((string)$s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/**
 * href 에 넣어도 되는 URL 인지 검사합니다.
 * 관리자가 입력한 값이 그대로 링크가 되므로, javascript: 같은 스킴이 저장되어도
 * 실행되지 않도록 http/https 만 통과시킵니다.
 */
function safe_url(?string $url): ?string
{
    $url = trim((string)$url);
    if ($url === '') {
        return null;
    }
    $scheme = strtolower((string)parse_url($url, PHP_URL_SCHEME));
    return in_array($scheme, ['http', 'https'], true) ? $url : null;
}

function obs_url(string $key): string
{
    return rtrim(OBS_BASE_URL, '/') . '/' . ltrim($key, '/');
}

function human_size(int $bytes): string
{
    $units = ['B', 'KB', 'MB', 'GB'];
    $i = 0;
    $n = (float)$bytes;
    while ($n >= 1024 && $i < count($units) - 1) {
        $n /= 1024;
        $i++;
    }
    return ($i === 0 ? (string)(int)$n : number_format($n, 1)) . ' ' . $units[$i];
}

/** OBS 의 UTC 타임스탬프를 표시용 현지 시각으로 바꿉니다. */
function fmt_date(?string $iso, string $format = 'Y-m-d'): string
{
    if (!$iso) {
        return '';
    }
    try {
        return (new DateTimeImmutable($iso))
            ->setTimezone(new DateTimeZone(DISPLAY_TZ))
            ->format($format);
    } catch (Exception $ex) {
        return '';
    }
}

